ALL_SECTIONS = [s for s in OPTIONAL_SECTIONS if s != "ai_insights"]


def _data(dataset, report_type="security_assessment", sections=ALL_SECTIONS, ai=None):
    content, findings = build_content(
        spec=SPECS[report_type],
        dataset=dataset,
        now=fx.NOW,
        period_label="Last 30 days",
        period_from=fx.NOW - timedelta(days=30),
        period_to=fx.NOW,
        sections=list(sections),
        scope={
            "providers": ["production-aws", "corp-azure"],
            "frameworks": [],
            "stale_days": 7,
        },
    )
    if ai is not None:
        content["ai"] = ai
        content["meta"]["sections"].append("ai_insights")
    data = ReportData(
        report_type=report_type,
        title=SPECS[report_type].title,
        generated_at=fx.NOW,
        filters=ReportFilters(),
    )
    legacy_fields(data, content, findings)
    data.extra["assessment"] = content
    data.assessment_findings = findings
    return data


def _write_sample(name: str, pdf: bytes) -> None:
    target = os.environ.get("CS_REPORT_SAMPLES_DIR")
    if target:
        Path(target).mkdir(parents=True, exist_ok=True)
        (Path(target) / f"{name}.pdf").write_bytes(pdf)


class TestPdfLayout:
    @pytest.mark.parametrize("report_type", sorted(SPECS))
    @pytest.mark.parametrize("sample", ["typical", "stale-partial", "empty"])
    def test_every_type_lays_out_cleanly(self, report_type, sample):
        dataset = fx.samples()[sample] if sample != "large" else fx.large_dataset(3000)
        data = _data(dataset, report_type)
        pdf = get_renderer("pdf")(data)
        assert pdf.startswith(b"%PDF")
        content = data.extra["assessment"]
        layout = content["layout"]
        assert layout["pages"] >= 3
        assert layout["blank_pages"] == []
        assert layout["orphan_headings"] == []
        assert layout["toc_entries"] >= 3
        assert layout["bookmarks"] == layout["toc_entries"]
        assert layout["metadata"]
        assert layout["page_total_consistent"]
        assert content["quality"]["distributable"], content["quality"]
        _write_sample(f"{report_type}-{sample}", pdf)

    def test_large_report_bounds_the_appendix(self):
        data = _data(fx.large_dataset(3000))
        pdf = render_assessment_pdf(data)
        content = data.extra["assessment"]
        assert content["appendix"]["truncated"] in (True, False)
        assert content["layout"]["blank_pages"] == []
        assert content["quality"]["distributable"], content["quality"]
        _write_sample("security_assessment-large", pdf)

    def test_ai_section_renders_and_is_labelled(self):
        ai = {
            "status": "ok",
            "message": "Generated by Seeker AI from this report's data.",
            "model": "model-x",
            "insights": [
                {
                    "statement": "Most exposure is in one account.",
                    "kind": "interpretation",
                    "citations": ["open_findings"],
                }
            ],
        }
        data = _data(fx.multi_cloud_dataset(), ai=ai)
        pdf = render_assessment_pdf(data)
        assert pdf.startswith(b"%PDF")
        checks = {
            c["id"]: c["status"] for c in data.extra["assessment"]["quality"]["checks"]
        }
        assert checks["ai_cited"] == "pass"
        _write_sample("security_assessment-with-ai", pdf)

    def test_metadata_and_fonts_are_embedded(self):
        pdf, layout = build_pdf(_data(fx.multi_cloud_dataset()).extra["assessment"])
        assert b"/Title" in pdf and b"/Author" in pdf and b"/Keywords" in pdf
        assert b"FontFile2" in pdf  # embedded TrueType (Unicode-capable)
        assert b"/Outlines" in pdf  # bookmarks
        assert b"/Annots" in pdf  # clickable contents links
        assert layout["pages"] > 5

    def test_unicode_text_renders(self):
        dataset = fx.multi_cloud_dataset()
        dataset.findings[0].title = "Zugriff für „Kunden“ — 東京 · résumé"
        pdf = render_assessment_pdf(_data(dataset))
        assert pdf.startswith(b"%PDF")

    def test_quality_failure_is_recorded_not_raised(self):
        data = _data(fx.multi_cloud_dataset())
        data.extra["assessment"]["methodology"].append("".join(("Pro", "wler")))
        render_assessment_pdf(data)
        assert data.extra["assessment"]["quality"]["distributable"] is False


class TestCsvExport:
    def test_one_traceable_row_per_unique_finding(self):
        data = _data(fx.duplicates_dataset())
        text = render_assessment_csv(data).decode("utf-8")
        assert text.startswith("﻿")
        rows = list(csv.reader(io.StringIO(text.lstrip("﻿"))))
        assert rows[0] == [header for _, header in CSV_COLUMNS]
        assert len(rows) - 1 == len(data.assessment_findings)
        header = rows[0]
        merged = next(
            r for r in rows[1:] if r[header.index("Source record id")] == "dup-b"
        )
        assert merged[header.index("Merged duplicate record ids")] == "dup-a"
        assert merged[header.index("Priority")] == "P1"

    def test_formulas_are_neutralized(self):
        dataset = fx.duplicates_dataset()
        dataset.findings[3].resource_name = '=HYPERLINK("x")'
        text = render_assessment_csv(_data(dataset)).decode("utf-8")
        assert "'=HYPERLINK" in text

    def test_csv_renderer_dispatches(self):
        data = _data(fx.multi_cloud_dataset())
        assert get_renderer("csv")(data) == render_assessment_csv(data)

    def test_json_and_xlsx_still_render(self):
        data = _data(fx.multi_cloud_dataset())
        assert b'"assessment"' in render_json(data)
        assert render_xlsx(data)[:2] == b"PK"


class TestQualityFlow:
    def test_quality_without_pdf_warns_about_layout(self):
        data = _data(fx.multi_cloud_dataset(), sections=DEFAULT_SECTIONS)
        result = quality.evaluate(
            data.extra["assessment"], data.assessment_findings, None
        )
        assert {c["id"]: c["status"] for c in result["checks"]}[
            "pdf_rendered"
        ] == "warn"
