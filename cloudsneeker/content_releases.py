"""Detection content release notes shipped with the product (EB-049).

``content/releases.json`` is generated by
``cloudsneeker/tools/content_release_notes.py`` from the upstream check and
compliance diff, newest release first. Depends only on the standard library.
"""

import json
from functools import cache
from pathlib import Path

RELEASES_PATH = Path(__file__).resolve().parent / "content" / "releases.json"


@cache
def load_releases() -> tuple[dict, ...]:
    """Releases newest first; empty when the notes are not packaged."""
    try:
        notes = json.loads(RELEASES_PATH.read_text(encoding="utf-8"))
    except FileNotFoundError:
        return ()
    return tuple(notes.get("releases") or ())
