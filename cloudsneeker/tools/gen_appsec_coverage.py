"""Generate ``knowledge-base/appsec-coverage.md`` from the capability matrix.

The matrix (``cloudsneeker_api/appsec/capabilities.py``) is the single source
for what the scan engine supports and what the product implements. Run this
after changing it::

    python cloudsneeker/tools/gen_appsec_coverage.py          # write the page
    python cloudsneeker/tools/gen_appsec_coverage.py --check  # fail if stale
"""

from __future__ import annotations

import argparse
import importlib.util
import sys
from collections import Counter
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
CAPABILITIES = (
    REPO_ROOT / "api" / "src" / "backend" / "cloudsneeker_api" / "appsec" / "capabilities.py"
)
OUTPUT = REPO_ROOT / "knowledge-base" / "appsec-coverage.md"

STATUS_ORDER = ("implemented", "partial", "missing", "unsupported", "not_applicable")


def load_capabilities():
    """Import the capability module by path (it imports nothing else)."""
    spec = importlib.util.spec_from_file_location("appsec_capabilities", CAPABILITIES)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def render(caps) -> str:
    """Return the Markdown page for the given capability module."""
    counts = Counter(feature["status"] for feature in caps.FEATURES)
    lines = [
        "# Application Security Coverage",
        "",
        "Generated by `cloudsneeker/tools/gen_appsec_coverage.py` from "
        "`cloudsneeker_api/appsec/capabilities.py`. Do not edit by hand.",
        "",
        f"Scan engine: Trivy {caps.ENGINE_VERSION} (pinned and checksum verified in "
        "`api/Dockerfile`). The matrix follows the CLI reference and Go types of "
        "that tag.",
        "",
        "## Status Meaning",
        "",
        "| Status | Meaning |",
        "| --- | --- |",
        "| Implemented | The product does it end to end. |",
        "| Partially Implemented | Part works; the detail says what does not. |",
        "| Missing | The engine can do it; the product does not yet. |",
        "| Unsupported | The engine cannot do it at the pinned version. |",
        "| Not Applicable | Deliberately not used in this product. |",
        "",
        "## Totals",
        "",
        "| Status | Capabilities |",
        "| --- | --- |",
    ]
    for status in STATUS_ORDER:
        lines.append(f"| {caps.STATUS_LABELS[status]} | {counts.get(status, 0)} |")
    lines += [
        f"| Total | {len(caps.FEATURES)} |",
        "",
        "## Target and Scanner Matrix",
        "",
        "| Target type | Engine command | Scanners | Default scanners | Exports | Experimental |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for key, target in caps.TARGETS.items():
        lines.append(
            f"| {target['label']} (`{key}`) | `{target['command']}` | "
            f"{', '.join(target['scanners'])} | {', '.join(target['default_scanners'])} | "
            f"{', '.join(target['export_formats'])} | "
            f"{'Yes' if target['experimental'] else 'No'} |"
        )
    lines += ["", "Not offered:", ""]
    for key, target in caps.UNAVAILABLE_TARGETS.items():
        lines.append(f"* {target['label']} (`{key}`): {_cell(target['reason'])}")
    lines += [
        "",
        "## Options by Target Type",
        "",
        "An option is listed for a target type only when that command accepts "
        "the flag. Profiles and targets cannot save any other combination.",
        "",
        "| Option | Flag | Target types |",
        "| --- | --- | --- |",
    ]
    for name, spec in caps.OPTION_SPECS.items():
        targets = [key for key, target in caps.TARGETS.items() if name in target["options"]]
        lines.append(f"| {_cell(spec['label'])} (`{name}`) | `{spec['flag']}` | {', '.join(targets)} |")
    lines += ["", "## Feature Coverage", ""]
    area = None
    for feature in caps.FEATURES:
        if feature["area"] != area:
            area = feature["area"]
            lines += [
                f"### {area}",
                "",
                "| Capability | Status | Detail |",
                "| --- | --- | --- |",
            ]
        lines.append(
            f"| {_cell(feature['feature'])} | {caps.STATUS_LABELS[feature['status']]} | "
            f"{_cell(feature['detail'])} |"
        )
        following = caps.FEATURES.index(feature) + 1
        if following == len(caps.FEATURES) or caps.FEATURES[following]["area"] != area:
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when the page is stale")
    args = parser.parse_args(argv)
    page = render(load_capabilities())
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.is_file() else ""
        if current.replace("\r\n", "\n") != page:
            print(f"{OUTPUT.relative_to(REPO_ROOT)} is stale; run this tool without --check.")
            return 1
        return 0
    OUTPUT.write_text(page, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
