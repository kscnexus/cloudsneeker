import { FileText } from "lucide-react";
import Link from "next/link";

import {
  assessmentSummary,
  QUALITY_STATUS,
  qualityLabel,
  scopeLabel,
} from "@/cloudsneeker/lib/assessment-wizard";
import { reportTitle } from "@/cloudsneeker/lib/report-catalog";
import {
  formatReportDate,
  isReportRunActive,
  reportStatusLabel,
  reportStatusTone,
} from "@/cloudsneeker/lib/report-view";
import {
  TABLE_BODY_CLASS,
  TABLE_CLASS,
  TABLE_FRAME_CLASS,
  TABLE_HEAD_CLASS,
  TABLE_HEADER_CELL_CLASS,
} from "@/cloudsneeker/lib/ui-classes";
import { reportsHref } from "@/cloudsneeker/routes";
import {
  REPORT_RUN_STATUS,
  type ReportRunResource,
} from "@/cloudsneeker/types/reports";
import { AutoRefresh } from "@/components/scans/auto-refresh";
import { Badge } from "@/components/shadcn";

import { EmptyState } from "./empty-state";
import { ReportDownloadLinks } from "./report-download-links";

const HEADERS = [
  "Report",
  "Period",
  "Scope",
  "Generated by",
  "Version",
  "Status",
  "Quality",
  "Files",
] as const;

interface AssessmentHistoryTableProps {
  runs: ReportRunResource[];
}

/** Generated assessment reports the user may see (API scopes by role). */
export const AssessmentHistoryTable = ({ runs }: AssessmentHistoryTableProps) => {
  if (runs.length === 0) {
    return (
      <EmptyState
        icon={<FileText />}
        title="No assessments yet"
        description="Use the wizard above to generate the first one."
      />
    );
  }
  const hasActiveRun = runs.some((run) => isReportRunActive(run.attributes.status));
  return (
    <div className="flex flex-col gap-2">
      <AutoRefresh hasExecutingScan={hasActiveRun} />
      <div className={TABLE_FRAME_CLASS}>
        <table className={TABLE_CLASS}>
          <thead className={TABLE_HEAD_CLASS}>
            <tr>
              {HEADERS.map((header) => (
                <th key={header} scope="col" className={TABLE_HEADER_CELL_CLASS}>
                  {header}
                </th>
              ))}
            </tr>
          </thead>
          <tbody className={TABLE_BODY_CLASS}>
            {runs.map((run) => {
              const attributes = run.attributes;
              const summary = assessmentSummary(attributes);
              const completed = attributes.status === REPORT_RUN_STATUS.COMPLETED;
              const name = reportTitle(attributes.report_type, attributes.report_name);
              const qualityTone =
                summary.distributable === false
                  ? "error"
                  : summary.qualityStatus === QUALITY_STATUS.WARN
                    ? "warning"
                    : summary.distributable
                      ? "success"
                      : "info";
              return (
                <tr key={run.id}>
                  <td className="px-3 py-2">
                    <div className="flex flex-col">
                      {completed ? (
                        <Link
                          href={reportsHref(run.id)}
                          className="text-text-neutral-primary font-medium underline-offset-2 hover:underline"
                        >
                          {name}
                        </Link>
                      ) : (
                        <span className="text-text-neutral-primary font-medium">{name}</span>
                      )}
                      <span className="text-text-neutral-tertiary text-xs">
                        {formatReportDate(attributes.inserted_at)}
                      </span>
                    </div>
                  </td>
                  <td className="text-text-neutral-secondary px-3 py-2 text-xs whitespace-nowrap">
                    {summary.period ?? attributes.params.period ?? "—"}
                  </td>
                  <td className="text-text-neutral-secondary max-w-56 px-3 py-2 text-xs">
                    {scopeLabel(summary, attributes.params.provider_ids?.length ?? 0)}
                  </td>
                  <td className="text-text-neutral-secondary px-3 py-2 text-xs">
                    {attributes.created_by_name ||
                      (attributes.trigger === "scheduled" ? "Schedule" : "—")}
                  </td>
                  <td className="text-text-neutral-secondary px-3 py-2 text-xs tabular-nums">
                    {summary.version ?? "—"}
                  </td>
                  <td className="px-3 py-2">
                    <Badge variant={reportStatusTone(attributes.status)}>
                      {reportStatusLabel(attributes.status)}
                    </Badge>
                    {attributes.status === REPORT_RUN_STATUS.FAILED && attributes.error ? (
                      <p className="text-text-error-primary mt-1 max-w-xs text-xs">
                        {attributes.error}
                      </p>
                    ) : null}
                  </td>
                  <td className="px-3 py-2">
                    {completed ? (
                      <Badge variant={qualityTone}>{qualityLabel(summary)}</Badge>
                    ) : (
                      <span className="text-text-neutral-tertiary text-xs">—</span>
                    )}
                  </td>
                  <td className="px-3 py-2">
                    <div className="flex flex-wrap gap-1">
                      {completed ? (
                        <ReportDownloadLinks
                          runId={run.id}
                          formats={attributes.available_formats ?? []}
                        />
                      ) : (
                        <span className="text-text-neutral-tertiary text-xs">—</span>
                      )}
                    </div>
                  </td>
                </tr>
              );
            })}
          </tbody>
        </table>
      </div>
    </div>
  );
};
